package com.gero.notifications.core;

/**
 * Immutable representation of the outcome of a notification dispatch operation.
 *
 * <p>Implemented as a Java record to encapsulate delivery status, unique upstream message
 * identifiers, and diagnostic failure details in an immutable, thread-safe value object.</p>
 *
 * @param success      {@code true} if the message was accepted or dispatched by the provider; {@code false} otherwise.
 * @param messageId    The unique tracking identifier assigned by the provider (e.g., SendGrid message ID, Twilio SID),
 *                     or {@code null} if the dispatch failed.
 * @param errorMessage A diagnostic message describing the cause of failure, or {@code null} if the operation succeeded.
 */
public record NotificationResult(boolean success, String messageId, String errorMessage) {

    /**
     * Factory method creating a successful dispatch result.
     *
     * @param messageId The unique identifier generated by the delivery provider.
     * @return A {@code NotificationResult} marked as successful containing the message ID.
     */
    public static NotificationResult success(String messageId) {
        return new NotificationResult(true, messageId, null);
    }

    /**
     * Factory method creating a failed dispatch result.
     *
     * @param errorMessage A descriptive error message explaining why the dispatch could not be completed.
     * @return A {@code NotificationResult} marked as failed containing the error details.
     */
    public static NotificationResult failure(String errorMessage) {
        return new NotificationResult(false, null, errorMessage);
    }
}